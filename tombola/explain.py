def explain(param):
    """(long, short) help lines for a setting at its current value; short fits narrow panes."""
    text = f"{param.label}: {HELP.get(param.key, param.label.title())}"
    extra = VALUES.get(param.key, {}).get(param.value)
    if not extra:
        return text, text
    return f"{text} — {param.value}: {extra}", f"{param.label} {param.value}: {extra}"
